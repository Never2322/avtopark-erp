_WORD = re.compile(r"[\W_]+", re.UNICODE)


def norm(text: str | None) -> str:
    """Название для сравнения: без регистра, без «ё», без знаков, слова через пробел."""
    return _WORD.sub(" ", (text or "").casefold().replace("ё", "е")).strip()
